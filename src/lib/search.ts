/**
 * 搜索匹配。
 *
 * 匹配规则：对歌曲名（title）或歌手（artist）做不区分大小写的子串匹配；
 * 结果排序：歌名前缀 > 歌名子串 > 歌手匹配；同一首歌只出现一次。
 */

export interface SearchMatch {
  /** 歌曲在 songs/cards 中的下标。 */
  index: number;
  title: string;
  artist: string;
  /** 命中类型：title / artist。 */
  kind: 'title' | 'artist';
  cover?: string;
  hue1?: number;
}

export interface SearchableSong {
  title: string;
  artist: string;
  cover?: string;
  hue1?: number;
}

